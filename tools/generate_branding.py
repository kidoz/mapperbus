#!/usr/bin/env python3
"""Regenerate checked-in brand assets. Requires librsvg and ImageMagick."""

import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets/branding"
SIZES = (16, 24, 32, 48, 64, 128, 256, 512, 1024)

# Original 5-by-7 pixel lettering; no font dependency.
GLYPHS = {
    "M": ("10001", "11011", "10101", "10001", "10001", "10001", "10001"),
    "A": ("01110", "10001", "10001", "11111", "10001", "10001", "10001"),
    "P": ("11110", "10001", "10001", "11110", "10000", "10000", "10000"),
    "E": ("11111", "10000", "10000", "11110", "10000", "10000", "11111"),
    "R": ("11110", "10001", "10001", "11110", "10100", "10010", "10001"),
    "B": ("11110", "10001", "10001", "11110", "10001", "10001", "11110"),
    "U": ("10001", "10001", "10001", "10001", "10001", "10001", "01110"),
    "S": ("01111", "10000", "10000", "01110", "00001", "00001", "11110"),
}

def render(svg, size, destination):
    subprocess.run(["rsvg-convert", "--width", str(size), "--height", str(size),
                    "--output", str(destination), str(svg)], check=True)


def generate():
    source = BRAND / "mapperbus-icon.svg"
    png_dir = BRAND / "png"
    png_dir.mkdir(exist_ok=True)
    (ROOT / "packaging/macos").mkdir(exist_ok=True)
    (ROOT / "packaging/windows").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        small = Path(temporary) / "small.svg"
        tree = ET.parse(source)
        for parent in tree.iter():
            for child in list(parent):
                if child.get("id") == "detail":
                    parent.remove(child)
        tree.write(small, encoding="unicode")
        for size in SIZES:
            selected = BRAND / "mapperbus-icon-small.svg" if size == 16 else small if size <= 32 else source
            render(selected, size, png_dir / f"mapperbus-{size}.png")

    rgba = subprocess.check_output(["magick", str(png_dir / "mapperbus-32.png"),
                                    "-depth", "8", "rgba:-"])
    if len(rgba) != 32 * 32 * 4:
        raise ValueError("Expected a 32-by-32 RGBA icon")
    rows = ["    " + ", ".join(f"0x{value:02x}" for value in rgba[index:index + 16]) + ","
            for index in range(0, len(rgba), 16)]
    (ROOT / "src/frontends/app_icon.hpp").write_text(
        "// Generated by tools/generate_branding.py; edit assets/branding/*.svg.\n"
        "#pragma once\n\n#include <array>\n\nnamespace mapperbus::frontend {\n\n"
        "inline constexpr std::array<unsigned char, 4096> kAppIconRgba = {\n"
        + "\n".join(rows) + "\n};\n\n} // namespace mapperbus::frontend\n")

    # Modern Windows supports PNG-compressed ICO frames, including alpha.
    ico_sizes = (16, 24, 32, 48, 64, 128, 256)
    offset = 6 + 16 * len(ico_sizes)
    entries, frames = [], []
    for size in ico_sizes:
        data = (png_dir / f"mapperbus-{size}.png").read_bytes()
        entries.append(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0,
                                   1, 32, len(data), offset))
        frames.append(data)
        offset += len(data)
    (ROOT / "packaging/windows/mapperbus.ico").write_bytes(
        struct.pack("<HHH", 0, 1, len(ico_sizes)) + b"".join(entries + frames))

    # Standard and Retina ICNS PNG representations.
    representations = {"icp4": 16, "icp5": 32, "icp6": 64, "ic07": 128,
                       "ic08": 256, "ic09": 512, "ic10": 1024,
                       "ic11": 32, "ic12": 64, "ic13": 256, "ic14": 512}
    chunks = []
    for kind, size in representations.items():
        data = (png_dir / f"mapperbus-{size}.png").read_bytes()
        chunks.append(kind.encode("ascii") + struct.pack(">I", len(data) + 8) + data)
    payload = b"".join(chunks)
    (ROOT / "packaging/macos/MapperBus.icns").write_bytes(
        b"icns" + struct.pack(">I", len(payload) + 8) + payload)
    shutil.copyfile(source, ROOT / "packaging/linux/dev.mapperbus.gui.svg")

    icon = source.read_text().split('</desc>', 1)[1].rsplit('</svg>', 1)[0]
    for variant, color in (("", "#112c51"), ("-light", "#f5f7fb")):
        pixels = []
        for index, letter in enumerate("MAPPERBUS"):
            for y, row in enumerate(GLYPHS[letter]):
                for x, pixel in enumerate(row):
                    if pixel == "1":
                        pixels.append(f'<rect x="{index * 6 + x}" y="{y}" width="1" height="1"/>')
        logo = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="224" '
            'viewBox="0 0 1024 224" role="img" aria-label="MapperBus">\n'
            '<title>MapperBus</title>\n'
            f'<g transform="translate(0 4) scale(.42)">{icon}</g>\n'
            f'<g transform="translate(270 70) scale(13)" fill="{color}">'
            + "".join(pixels) + '</g>\n</svg>\n')
        destination = BRAND / f"mapperbus-logo{variant}.svg"
        destination.write_text(logo)
    print("Generated SVG logos, Linux SVG, 9 PNG sizes, Windows ICO, and macOS ICNS.")


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    if not all(shutil.which(tool) for tool in ("rsvg-convert", "magick")):
        raise SystemExit("Install librsvg (rsvg-convert) and ImageMagick (magick) before regenerating branding.")
    generate()


if __name__ == "__main__":
    main()
